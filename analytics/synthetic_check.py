"""Heuristics that flag synthetic / generated data posing as real sensor data.

Each check returns findings with a severity (HIGH = strong evidence of generation).
Usage:  .venv/bin/python -m analytics.synthetic_check <file> [--label COL ...] [--time-col COL] [--id-col COL]
"""
import argparse

import numpy as np
import pandas as pd
from sklearn.model_selection import cross_val_score
from sklearn.tree import DecisionTreeClassifier

from . import load_table

SEEDS = (0, 1, 7, 42, 123, 1234, 2024, 2025)


def _streams(seed: int, size: int) -> dict[str, np.ndarray]:
    return {
        "RandomState.normal": np.random.RandomState(seed).normal(size=size),
        "RandomState.uniform": np.random.RandomState(seed).uniform(size=size),
        "default_rng.normal": np.random.default_rng(seed).normal(size=size),
        "default_rng.random": np.random.default_rng(seed).random(size=size),
    }


def check_seeded_rng(df: pd.DataFrame, n: int = 30, max_rows: int = 100_000) -> list[dict]:
    """Column values are an exact affine transform of numpy draws for a common seed.

    Columns generated one after another from the same RNG appear at offsets k*len(df) of the stream,
    so offsets 0..n_cols-1 (times the row count) are tested too.
    """
    num = df.select_dtypes("number")
    num = num.loc[:, num.nunique() > n]
    if num.empty:
        return []
    rows = min(len(df), max_rows)
    found = []
    for seed in SEEDS:
        for kind, z in _streams(seed, rows * (num.shape[1] + 1)).items():
            for c in num.columns:
                x = num[c].to_numpy()[:n].astype(float)
                if np.isnan(x).any():
                    continue
                for k in range(num.shape[1] + 1):
                    seg = z[k * rows : k * rows + n]
                    if len(seg) == n and abs(np.corrcoef(x, seg)[0, 1]) > 0.9999:
                        found.append({"check": "seeded_rng", "severity": "HIGH", "column": c,
                                      "detail": f"values = a + b*{kind}(seed={seed}) at stream offset {k}x{rows}"})
                        break
    return found


def check_independence(df: pd.DataFrame, id_col: str | None) -> list[dict]:
    """Real multi-sensor data is correlated and autocorrelated; i.i.d. noise is not."""
    num = df.select_dtypes("number").drop(columns=[id_col] if id_col in df else [], errors="ignore")
    num = num.loc[:, num.nunique() > 10]
    out = []
    if num.shape[1] >= 3:
        c = num.corr().abs().to_numpy()
        off = c[~np.eye(len(c), dtype=bool)]
        if np.nanmax(off) < 0.02:
            out.append({"check": "cross_sensor_independence", "severity": "MEDIUM",
                        "detail": f"all {num.shape[1]} numeric columns mutually uncorrelated (max |r|={np.nanmax(off):.4f})"})
    groups = df.groupby(id_col) if id_col and id_col in df else [(None, df)]
    ac = {}
    for col in num.columns:
        vals = [g[col].autocorr(1) for _, g in groups if len(g) > 50]
        ac[col] = float(np.nanmean(vals)) if vals else np.nan
    white = [k for k, v in ac.items() if pd.notna(v) and abs(v) < 0.3]
    if white and len(white) == len(ac):
        out.append({"check": "white_noise", "severity": "MEDIUM",
                    "detail": f"lag-1 autocorrelation < 0.3 for all signals (real physical signals are smooth) "
                              f"{dict((k, round(ac[k], 3)) for k in white)}"})
    return out


def check_derived_columns(df: pd.DataFrame) -> list[dict]:
    num = df.select_dtypes("number")
    num = num.loc[:, num.nunique() > 10]
    out, cols = [], list(num.columns)
    for i, a in enumerate(cols):
        for b in cols[i + 1:]:
            for fn, name in ((lambda v: v, "linear"), (np.square, "square")):
                r = np.corrcoef(num[a].fillna(0), fn(num[b].fillna(0)))[0, 1]
                if abs(r) > 0.9995:
                    out.append({"check": "derived_column", "severity": "LOW", "detail": f"`{a}` is a {name} function of `{b}` (r={r:.5f})"})
                    break
    return out


def check_exact_rules(df: pd.DataFrame, labels: list[str]) -> list[dict]:
    """A depth<=3 tree reproducing a rare label perfectly suggests the label was generated by a threshold rule."""
    out = []
    X = df.select_dtypes("number").drop(columns=labels, errors="ignore").fillna(0)
    X = X.loc[:, (X.nunique() < len(X)) & (X.nunique() > 1)]
    base = list(X.columns)[:12]
    derived = {}
    for i, a in enumerate(base):
        for b in base[i + 1:]:
            derived[f"{a}-{b}"] = X[a] - X[b]
            derived[f"{a}*{b}"] = X[a] * X[b]
    X = pd.concat([X, pd.DataFrame(derived, index=X.index)], axis=1)
    for lab in labels:
        y = df[lab]
        if y.nunique() < 2 or y.value_counts(normalize=True).min() > 0.2:
            continue
        for depth in (1, 2, 3):
            clf = DecisionTreeClassifier(max_depth=depth, random_state=0)
            acc = cross_val_score(clf, X, y, cv=3, scoring="balanced_accuracy").mean()
            if acc > 0.995:
                clf.fit(X, y)
                used = sorted({X.columns[i] for i in clf.tree_.feature if i >= 0})
                out.append({"check": "exact_rule_label", "severity": "HIGH", "column": lab,
                            "detail": f"depth-{depth} tree reproduces label (balanced acc {acc:.4f}) using {used}"})
                break
    return out


def check_time_regularity(df: pd.DataFrame, time_col: str | None) -> list[dict]:
    if not time_col or time_col not in df:
        return []
    t = pd.to_datetime(df[time_col], errors="coerce").dropna()
    out = []
    is_period_data = (t.dt.normalize() == t).all() and (t.dt.day.nunique() == 1 or t.dt.dayofweek.nunique() == 1)
    if len(t) > 50 and not is_period_data:
        top_hour_share = t.dt.hour.value_counts(normalize=True).iloc[0]
        if top_hour_share > 0.9 and t.dt.hour.nunique() <= 3:
            out.append({"check": "fixed_clock_events", "severity": "MEDIUM",
                        "detail": f"{top_hour_share:.0%} of events at hour {t.dt.hour.mode()[0]}:00"})
        if t.dt.second.nunique() == 1 and t.dt.minute.nunique() == 1 and t.dt.hour.nunique() > 3:
            hourly = t.dt.hour.value_counts(normalize=True)
            if hourly.max() - hourly.min() < 0.01:
                out.append({"check": "no_daily_cycle", "severity": "LOW", "detail": "perfectly uniform hourly sampling with no gaps"})
    return out


def run(df, labels=(), time_col=None, id_col=None) -> list[dict]:
    return (check_seeded_rng(df) + check_independence(df, id_col) + check_derived_columns(df)
            + check_exact_rules(df, list(labels)) + check_time_regularity(df, time_col))


def verdict(findings: list[dict]) -> str:
    high = sum(f["severity"] == "HIGH" for f in findings)
    med = sum(f["severity"] == "MEDIUM" for f in findings)
    if high:
        return "LIKELY SYNTHETIC"
    if med >= 2:
        return "SUSPICIOUS (probably synthetic)"
    if med == 1:
        return "INCONCLUSIVE"
    return "NO SYNTHETIC SIGNATURES FOUND (not proof of being real)"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("file")
    ap.add_argument("--label", action="append", default=[])
    ap.add_argument("--time-col")
    ap.add_argument("--id-col")
    ap.add_argument("--nrows", type=int, default=200_000)
    a = ap.parse_args()
    df = load_table(a.file, nrows=a.nrows)
    f = run(df, a.label, a.time_col, a.id_col)
    print(f"VERDICT: {verdict(f)}")
    for x in f:
        print(f"[{x['severity']}] {x['check']}: {x.get('column', '')} {x['detail']}")


if __name__ == "__main__":
    main()
